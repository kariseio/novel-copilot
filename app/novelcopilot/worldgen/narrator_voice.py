def find_protagonist_id(ont) -> str:
    """1인칭 서술자로 결속할 주인공 id — entities 삽입순 첫 actor(없으면 "").

    harness.HarnessGenerator._pov_entity_id 의 pov 분기 이후 본문과 *동형 규칙*이다(entities 삽입순 첫 actor).
    거기는 self.style.pov=='first' 게이트를 먼저 통과한 뒤 이 루프를 돈다 — 여기서는 pov 게이트를 호출부가
    지고(서비스는 world.style.pov 로 판정), 이 함수는 순수 '첫 actor' 도출만 담당한다(단일 규칙·중복 없음)."""
    for e in ont.entities.values():
        if ont.is_actor(e.etype):
            return e.id
    return ""


@promptlog.stage("worldgen:voice_card")
def derive_voice_card(provider, world, protagonist_id: str) -> str:
    """주인공 시트(profile)+작품 톤+전제 → 서술자 음성 카드(≤600자). LLM 1콜.

    NEVER throws — 파싱 실패·비정형 반환·근거 부재는 전부 ""(무주입). 근거 소스(profile) 자체가 비면 스킵.
    긍정 전용(프롬프트·스키마에 금지문·틱 이름 호명 0). 반환값은 호출부가 entity.voice 에 영속한다."""
    prota = None
    for e in getattr(world, "entities", None) or []:
        if e.id == protagonist_id:
            prota = e
            break
    if prota is None:
        return ""
    profile = (getattr(prota, "profile", "") or "").strip()
    if not profile:                       # 근거(주인공 설계서) 없음 → 발명 방지·무주입
        return ""
    src = json.dumps({
        "protagonist": {"name": getattr(prota, "name", ""), "profile": profile},   # 절단 전면 제거(2026-08-21): 파생 입력 전문
        "tone": getattr(world, "tone", "") or "",
        "premise": getattr(world, "premise", "") or "",
    }, ensure_ascii=False)
    try:
        d = provider.chat_json(
            [{"role": "system", "content": _SYSTEM}, {"role": "user", "content": f"[주인공 시트·톤·전제]\n{src}"}],
            temperature=0.5)
    except Exception:
        return ""
    if not isinstance(d, dict):
        return ""
    card = d.get("card")
    card = card.strip() if isinstance(card, str) else ""   # 비문자열(int/None/list) → ""(NEVER throws)
    return card[:600]                     # 방어적 길이 cap(설계 상한 600자 — draft 헤더 주입이라 짧게)
